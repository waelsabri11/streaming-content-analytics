"""Generate reports/results.md (and the README key-numbers block) from the JSON/JSONL result files.

Every number quoted in README.md comes from reports/results.md, which is written by this script from
reports/results/*.json and timings.jsonl. `python reports/make_results.py --check` fails if the README
key-numbers block is out of date.
"""

from __future__ import annotations

import json
import platform
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "reports" / "results"
README = ROOT / "README.md"
BEGIN, END = "<!-- KEY-NUMBERS:BEGIN (generated by reports/make_results.py) -->", "<!-- KEY-NUMBERS:END -->"


def load(name: str) -> dict:
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else {}


def timings() -> dict[str, dict]:
    out: dict[str, dict] = {}
    p = RES / "timings.jsonl"
    if p.exists():
        for line in p.read_text().splitlines():
            r = json.loads(line)
            out[r["step"]] = r  # latest wins
    return out


def md_table(rows: list[list], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def f(x, d=3):
    return "n/a" if x is None else f"{x:,.{d}f}"


def n(x):
    return f"{int(x):,}"


def build() -> tuple[str, str]:
    T, nf, sg, lc, tu = timings(), load("netflix"), load("twitch_segments"), load("twitch_lifecurves"), load("tuning")
    env = load("environment")
    out = ["# Results\n", "Generated by `python reports/make_results.py` from `reports/results/*.json` and `timings.jsonl`. "
           "Do not edit by hand.\n"]
    key: list[str] = []

    # ---------------- volumes and timings
    out.append("## 1. Data volumes processed and pipeline timings\n")
    if env:
        out.append(f"Run environment: {env.get('platform')}, {env.get('cpus')} CPU threads, {env.get('ram_gb')} GB RAM, "
                   f"Spark {env.get('spark')}, Delta {env.get('delta')}, `local[*]` (not Databricks; see README).\n")
    rows = []
    for step, label in [("bronze_ingest", "Bronze: gzip CSV -> Delta (one unsplittable gzip task)"),
                        ("silver_streamer_dim", "Silver: channel dictionary"),
                        ("silver_sessionize", "Silver: clean + dedupe + sessionize (window by viewer)"),
                        ("gold_sessions", "Gold: sessions table"),
                        ("gold_features", "Gold: per-viewer features (full window)"),
                        ("gold_features_h1", "Gold: per-viewer features, first half"),
                        ("gold_features_h2", "Gold: per-viewer features, second half"),
                        ("segments_select_k", "MLlib: k sweep (silhouette + bootstrap ARI) on a 2% sample"),
                        ("segments_fit_final", "MLlib: final KMeans on all viewers"),
                        ("segments_als", "MLlib: implicit ALS + channel families (first half, 10% viewers)"),
                        ("lifecurves_user_channel_day", "Life curves: viewer x channel x day table"),
                        ("lifecurves_channel_daily", "Life curves: channel daily new/returning viewers"),
                        ("lifecurves_retention", "Life curves: retention by first-contact week"),
                        ("netflix_total", "Netflix: parse, IMDb match, score, curves, value index")]:
        if step in T:
            r = T[step]
            vol = r.get("rows") or r.get("viewers") or r.get("sessions") or r.get("streamers") or r.get("titles_in_cohort") or ""
            rows.append([label, f"{r['seconds']:,.0f} s", n(vol) if vol != "" else ""])
    out.append(md_table(rows, ["Step", "Wall time", "Rows / entities out"]) + "\n")
    if "bronze_ingest" in T:
        key.append(f"| Twitch interactions processed (bronze rows) | {n(T['bronze_ingest']['rows'])} |")
    if "silver_sessionize" in T:
        key.append(f"| Silver rows after validation/dedup (rows dropped: {n(T['bronze_ingest']['rows'] - T['silver_sessionize']['rows'])}) | {n(T['silver_sessionize']['rows'])} |")
    if "gold_sessions" in T:
        key.append(f"| Viewer sessions (gap rule 3 slots = 30 min) | {n(T['gold_sessions']['sessions'])} |")
    if "gold_features" in T:
        key.append(f"| Viewers segmented | {n(T['gold_features']['viewers'])} |")
    if "silver_streamer_dim" in T:
        key.append(f"| Channels | {n(T['silver_streamer_dim']['streamers'])} |")
    if "silver_sessionize" in T:
        key.append(f"| Sessionization wall time, full 474M rows (local[*]) | {T['silver_sessionize']['seconds']:,.0f} s |")

    # ---------------- tuning
    if tu:
        out.append("\n## 2. Spark tuning experiments (10% viewer sample, local[*])\n")
        out.append(f"Sample: {n(tu['sample_rows'])} rows, {n(tu['sample_users'])} viewers. Median of runs; wall seconds.\n")
        rows = [[f"shuffle partitions = {k} (AQE off)" if k.isdigit() else "AQE on, 192 partitions", v["median_s"]]
                for k, v in tu["E1_shuffle_partitions"].items()]
        out.append("**E1 - shuffle partitions for the viewer-keyed window**\n\n" + md_table(rows, ["Setting", "Median s"]) + "\n")
        rows = [[k, v["median_s"]] for k, v in tu["E2_join"].items()]
        out.append("\n**E2 - channel dimension join (790k rows)**\n\n" + md_table(rows, ["Strategy", "Median s"]) + "\n")
        rows = [[k, v["median_s"]] for k, v in tu["E3_skewed_distinct"].items()]
        out.append("\n**E3 - distinct viewers per channel (skewed keys)**\n\n" + md_table(rows, ["Strategy", "Median s"]) + "\n")
        rows = [[k, v.get("median_s", v.get("error", ""))] for k, v in tu["E4_layout"].items() if k != "files"]
        out.append("\n**E4 - point lookup of 2,000 viewers by file layout**\n\n" + md_table(rows, ["Layout", "Median s"]) + "\n")
        out.append(f"\nFiles per layout: {tu['E4_layout'].get('files')}\n")
        out.append(f"\nSkew: intervals per viewer {tu['intervals_per_viewer']}; intervals per channel {tu['intervals_per_channel']}\n")

    # ---------------- segmentation
    if sg:
        out.append("\n## 3. Viewer segmentation (Spark MLlib)\n")
        rows = [[s["k"], f(s["silhouette"]), f(s["bootstrap_ari_mean"]), f(s["bootstrap_ari_min"])] for s in sg["k_sweep"]]
        out.append(md_table(rows, ["k", "Silhouette (2% sample)", "Bootstrap ARI mean", "Bootstrap ARI min"]) + "\n")
        out.append(f"\nSelection rule (fixed before looking at results): among k in {sg['k_candidates']} with mean bootstrap ARI >= {sg['ari_floor']}, "
                   f"the highest silhouette; chosen k = **{sg['k']}**. Sample size {n(sg['k_sweep'][0]['n_sample'])} viewers.\n")
        if "kmeans_seed_stability" in sg:
            s = sg["kmeans_seed_stability"]
            out.append(f"\nSame sample, 4 different KMeans seeds (k={s['k']}): pairwise ARI mean {f(s['ari_pairwise_mean'])}, min {f(s['ari_pairwise_min'])}.\n")
        prof = sg["profile"]
        rows = [[p["segment"], p["name"], n(p["n_viewers"]), f"{p['viewer_share']:.1%}", f"{p['hours_share']:.1%}", f(p["hours"], 1), f(p["n_sessions"], 1),
                 f(p["active_days"], 1), f(p["n_streamers"], 1), f(p["top1_share"], 2), f(p["repeat_share"], 2), f(p["share_night"], 2), f(p["share_evening"], 2)]
                for p in prof]
        out.append("\n" + md_table(rows, ["Seg", "Name", "Viewers", "Viewer share", "Watch-time share", "Hours", "Sessions", "Active days",
                                          "Channels", "Top-1 share", "Repeat share", "Clock 00-06h", "Clock 18-24h"]) + "\n")
        th = sg["time_halves"]
        out.append(f"\n**Stability across time halves** ({n(th['viewers_active_in_both_halves'])} viewers active in both halves): "
                   f"ARI between the first-half model and the second-half model applied to second-half features = {f(th['ari_model_h1_vs_model_h2_on_h2_features'])}; "
                   f"ARI of the same first-half model on a viewer's first- vs second-half features = {f(th['ari_same_model_h1_features_vs_h2_features'])}; "
                   f"{th['share_viewers_same_segment_h1_to_h2']:.1%} of viewers stay in the same segment.\n")
        pv = sg["predictive_validity"]
        out.append(f"\n**Predictive validity** (first-half segment -> second-half outcome, n={n(pv['n_sample'])} sampled viewers): "
                   f"eta^2 of log(1+second-half hours) by segment = {f(pv['eta2_log_hours_h2_by_segment'])}; by first-half hours decile = {f(pv['eta2_log_hours_h2_by_h1_hours_decile'])}; "
                   f"by first-half hours in {pv.get('equal_k_groups', 'k')} equal-size groups = {f(pv.get('eta2_log_hours_h2_by_h1_hours_equal_k_groups'))}. "
                   f"Share active in second half by segment: {pv['retained_in_h2_by_segment']}.\n")
        av = sg["als_variant"]["variants"]
        rows = [[k, v["n_features"], f(v["bootstrap_ari_mean"]), f(v["eta2_log_hours_h2"]), f(v["eta2_retained_h2"])] for k, v in av.items()]
        out.append("\n**ALS channel-affinity embeddings as extra input** (first-half data only; ALS "
                   f"{sg['als']['n_train_users']:,} viewers x {sg['als']['n_channels_with_factors']:,} channels, rank {sg['als']['rank']}, {sg['als']['n_families']} channel families)\n\n"
                   + md_table(rows, ["Variant", "Features", "Bootstrap ARI", "eta^2 log hours H2", "eta^2 active H2"]) + "\n")
        out.append("\n**Top over-indexed channels per segment** (lift = segment's watch-time share on the channel / everyone's; channels with >= 5,000 viewers overall, >= 500 in the segment)\n\n")
        for sid, items in sg["channel_affinity_top"].items():
            name = next(p["name"] for p in prof if str(p["segment"]) == sid)
            out.append(f"- Segment {sid} ({name}): " + ", ".join(f"{i['channel']} ({i['lift']}x)" for i in items[:5]) + "\n")
        out.append(f"\nWatch share by dataset-clock hour (hour 0..23): {sg['diurnal_watch_share_by_clock_hour']}\n" if "diurnal_watch_share_by_clock_hour" in sg else "")
        key.append(f"| Chosen k (bootstrap ARI {f(next(s for s in sg['k_sweep'] if s['k'] == sg['k'])['bootstrap_ari_mean'])}, silhouette {f(next(s for s in sg['k_sweep'] if s['k'] == sg['k'])['silhouette'])}) | {sg['k']} |")
        key.append(f"| Viewers staying in the same segment first half -> second half | {th['share_viewers_same_segment_h1_to_h2']:.1%} |")
        key.append(f"| eta^2 (H2 log hours): segments / hours in equal-size groups | {f(pv['eta2_log_hours_h2_by_segment'])} / {f(pv.get('eta2_log_hours_h2_by_h1_hours_equal_k_groups'))} |")
        key.append(f"| ALS embeddings: bootstrap ARI behaviour-only vs +embedding | {f(av['behaviour_only']['bootstrap_ari_mean'])} vs {f(av['behaviour_plus_embedding']['bootstrap_ari_mean'])} |")

    # ---------------- twitch life curves
    if lc:
        out.append("\n## 4. Twitch channel life curves\n")
        out.append(f"Channel-days: {n(lc['channel_days'])}; channels: {n(lc['channels'])}; channels born inside the window ({lc['born_in_window']['rule']}): {n(lc['born_in_window']['channels'])}.\n")
        ret = lc["retention_pair_weeks"]
        lags = sorted({int(lg) for row in ret.values() for lg in row})
        rows = [[f"week {w}"] + [f"{row.get(str(lg), ''):.3f}" if str(lg) in row else "" for lg in lags] for w, row in sorted(ret.items(), key=lambda kv: int(kv[0]))]
        out.append("\n**Retention of viewer-channel pairs** (share of pairs first seen in week w that are active again `lag` weeks later)\n\n"
                   + md_table(rows, ["First contact"] + [f"+{lg}w" for lg in lags]) + "\n")
        rows = []
        for tier, r in lc["decay"].items():
            rows.append([tier, n(r["n_channels"]), f(r["exponential"]["holdout_rmse_log"]), f(r["power"]["holdout_rmse_log"]), f(r["persistence"]["holdout_rmse_log"]),
                         f(r["exponential"]["shape"], 4), f(r["power"]["shape"], 3), r["returning_share_by_age"].get("1", r["returning_share_by_age"].get(1)) and f(r["returning_share_by_age"].get("1", 0), 2),
                         f(r["returning_share_by_age"].get("14", 0), 2)])
        out.append("\n**Decay fits on new channels** (fit on ages 1-14, hold-out ages 15-28; RMSE of log daily viewers)\n\n"
                   + md_table(rows, ["Tier (first-week size)", "Channels", "RMSE exponential", "RMSE power", "RMSE persistence", "Exp. rate/day", "Power gamma", "Returning share age 1", "Returning share age 14"]) + "\n")
        for tier, r in lc["decay"].items():
            key.append(f"| Twitch new-channel decay hold-out RMSE (log), {tier}: exp / power / persistence | {f(r['exponential']['holdout_rmse_log'], 2)} / {f(r['power']['holdout_rmse_log'], 2)} / {f(r['persistence']['holdout_rmse_log'], 2)} |")

    # ---------------- netflix
    if nf:
        v = nf["volumes"]
        out.append("\n## 5. Netflix titles\n")
        out.append(f"Parsed {n(v['bronze_rows'])} title-semester rows from {v['semesters']} semesters (H1 2023 - H1 2026); {n(v['titles_with_release_date'])} titles have a release date; "
                   f"{n(v['views_imputed_from_hours_over_runtime'])} rows have views derived as hours / runtime (all of 2023H1, which has no Views column).\n")
        m = nf["imdb_match"]
        out.append(f"\n**IMDb matching** (titles released since 2023-01-01, event-like rows excluded): {n(m['matched'])} / {n(m['n_titles'])} = {m['match_rate']:.1%}; "
                   f"series seasons {m['match_rate_series_seasons']:.1%}; films and other programmes {m['match_rate_other']:.1%}. Reasons: {m['reasons']}.\n")
        c = nf["cohort"]
        out.append(f"\n**Score cohort**: {n(c['n_titles'])} titles with a release date >= 2023-01-01 observed in their release semester; by release semester {c['by_release_semester']}; "
                   f"by kind {c['by_kind']}; {c['imdb_matched_share']:.1%} matched to IMDb.\n")
        rows = []
        for sem, fo in nf["score"]["folds"].items():
            for mname in ("lightgbm", "genre_median", "prior_season"):
                mm = fo[mname]
                rows.append([sem, mname, n(fo["n_test"]), f(mm["spearman"]), f(mm["top_decile_precision"]), f(mm["mae_log"]), f(mm["mape_log_scale"], 4), f(mm["median_ape_views"], 3)])
        out.append("\n**Performance score, temporal folds** (target: log views in release semester; train on cohorts released >= 2 semesters before the test semester, "
                   "conformal calibration on the previous semester)\n\n"
                   + md_table(rows, ["Test semester", "Model", "n test", "Spearman", "Top-decile precision", "MAE (log)", "MAPE on log scale", "Median APE (views)"]) + "\n")
        rows = []
        for sem, fo in nf["score"]["folds"].items():
            cf = fo["conformal"]
            rows.append([sem, f"{cf['target_coverage']:.0%}", f"{cf['empirical_coverage']:.1%}", f"x{2.718281828 ** (2 * cf['halfwidth_log']):.1f}"])
        out.append("\n**Split-conformal 80% intervals**\n\n" + md_table(rows, ["Test semester", "Target", "Empirical coverage", "Interval width (upper / lower views)"]) + "\n")
        rows = []
        for sem, fo in nf["score"]["folds"].items():
            if "on_titles_with_prior_season" in fo:
                o = fo["on_titles_with_prior_season"]
                rows.append([sem, o["n"], f(o["lightgbm"]["spearman"]), f(o["prior_season"]["spearman"]), f(o["lightgbm"]["mae_log"]), f(o["prior_season"]["mae_log"])])
        out.append("\n**Subset with a usable prior season** (pre-release information the baseline can use)\n\n"
                   + md_table(rows, ["Test semester", "n", "Spearman LightGBM", "Spearman prior-season", "MAE log LightGBM", "MAE log prior-season"]) + "\n")
        out.append("\n**SHAP, top features (last fold)**: " + ", ".join(f"{s['feature']} ({s['mean_abs_shap']:.2f})" for s in nf["score"]["shap_top"][:10]) + "\n")
        last = nf["score"]["primary_fold"]
        fo = nf["score"]["folds"][last]
        key.append(f"| Netflix score, {last} fold: Spearman LightGBM / genre-median / prior-season | {f(fo['lightgbm']['spearman'], 2)} / {f(fo['genre_median']['spearman'], 2)} / {f(fo['prior_season']['spearman'], 2)} |")
        key.append(f"| Netflix score, {last}: top-decile precision LightGBM / genre-median | {f(fo['lightgbm']['top_decile_precision'], 2)} / {f(fo['genre_median']['top_decile_precision'], 2)} |")
        key.append(f"| Conformal 80% interval empirical coverage, {last} (n={fo['n_test']}) | {fo['conformal']['empirical_coverage']:.1%} |")
        key.append(f"| IMDb match rate (cohort) | {m['match_rate']:.1%} |")

        lcv = nf["life_curves"]
        rows = []
        for kind, r in lcv["by_kind"].items():
            rows.append([kind, n(r["n_titles"]), f(r["exp_rate_per_day"], 4), f(r["exp_half_life_days"], 0), f(r["power_gamma"], 2), r["power_tau_days"],
                         f(r["within_title_mse_log_exponential"]), f(r["within_title_mse_log_power"])])
        out.append(f"\n**Netflix life curves** ({n(lcv['n_curve_points'])} title-semester points, {n(lcv['n_titles'])} titles released since 2023; {lcv['share_points_at_reporting_floor']:.1%} of points sit at the 100k-view reporting floor and are excluded from fits)\n\n"
                   + md_table(rows, ["Kind", "Titles", "Exp. rate/day", "Half-life (days)", "Power gamma", "Power tau (days)", "Within-title MSE exp", "Within-title MSE power"]) + "\n")
        vv = nf["value_index_validation"]
        for key_obs, label in (("observed_1_semester", "first semester observed"), ("observed_2_semester", "first two semesters observed")):
            b = vv[key_obs]
            rows = [[mn, f(b["survivors"][mn]["spearman"]), f(b["survivors"][mn]["median_ape"]), f(b["survivors"][mn]["mean_log_ratio"]),
                     f(b["all"][mn]["spearman"]), f(b["all"][mn]["median_ape"])] for mn in b["survivors"]]
            out.append(f"\n**Value index hold-out, {label}** (test cohorts {vv['test_cohorts']}, n={b['n_titles']}, drop-out share {b['dropout_share']:.1%}; shapes fitted on cohorts {vv['shape_train']['cohorts']} using observations up to {vv['shape_train']['observations_until']}; "
                       f"target = views in the remaining semesters up to semester {vv['horizon_semesters']})\n\n"
                       + md_table(rows, ["Method", "Spearman (survivors)", "Median APE (survivors)", "Mean log(pred/real) (survivors)", "Spearman (all)", "Median APE (all)"]) + "\n")
        b1 = vv["observed_1_semester"]["survivors"]
        key.append(f"| Value-index hold-out Spearman (1 semester observed): power / exponential / median-ratio / persistence | {f(b1['power']['spearman'], 2)} / {f(b1['exponential']['spearman'], 2)} / {f(b1['median_ratio']['spearman'], 2)} / {f(b1['persistence']['spearman'], 2)} |")
        key.append(f"| Value-index hold-out median APE (1 semester observed): power / exponential / median-ratio / persistence | {f(b1['power']['median_ape'], 2)} / {f(b1['exponential']['median_ape'], 2)} / {f(b1['median_ratio']['median_ape'], 2)} / {f(b1['persistence']['median_ape'], 2)} |")
        vi = nf["value_index"]
        rows = [[t["title"], t["kind"], t["rel_sem"], f"{t['value_views'] / 1e6:,.1f} M", f(t["value_index"], 1)] for t in vi["top10"]]
        out.append(f"\n**Value index, top 10** (cumulative views over {vi['horizon_semesters']} semesters since release, observed + forecast; {n(vi['n_fully_observed'])} of {n(vi['n_titles'])} titles fully observed)\n\n"
                   + md_table(rows, ["Title", "Kind", "Release semester", "Value (views)", "Index vs kind median"]) + "\n")
        mf = nf["score"].get("mlflow") or {}
        out.append(f"\nMLflow: {mf}\n")

    er = load("earlier_run")
    if er:
        out.append(f"\n## 6. Superseded first segmentation run\n\n{er['note']} Single-seed KMeans chose k = {er['k_chosen']} with bootstrap ARI {er['k5_bootstrap_ari_mean']}; "
                   f"the seed-only pairwise ARI of the same sample at k = {er['k_chosen']} was {er['seed_only_ari_pairwise_mean_k5']} (min {er['seed_only_ari_pairwise_min_k5']}). "
                   "KMeans restarts (best of 3) were then added and all segmentation results above come from the rerun.\n")
    return "\n".join(out) + "\n", "\n".join(["| Quantity | Value |", "|---|---|"] + key)


def main() -> None:
    env = {"platform": f"{platform.system()} {platform.machine()}", "python": platform.python_version()}
    results, snippet = build()
    (ROOT / "reports" / "results.md").write_text(results)
    block = f"{BEGIN}\n{snippet}\n{END}"
    if "--check" in sys.argv:
        text = README.read_text()
        ok = block in text
        print("README key-numbers block is", "up to date" if ok else "OUT OF DATE")
        sys.exit(0 if ok else 1)
    if README.exists() and BEGIN in README.read_text():
        t = README.read_text()
        a, b = t.index(BEGIN), t.index(END) + len(END)
        README.write_text(t[:a] + block + t[b:])
    print(f"wrote reports/results.md ({len(results.splitlines())} lines); env={env}")


if __name__ == "__main__":
    main()
